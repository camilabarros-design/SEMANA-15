function renderFavoritos() {
  var usuario = JSON.parse(sessionStorage.getItem("usuarioCorrente"));
  if (!usuario) {
    window.location.href = "modulos/login/index.html";
    return;
  }

  var saudacao = document.getElementById("favoritos-saudacao");
  if (saudacao) saudacao.textContent = "Olá, " + usuario.nome + "! Aqui estão seus locais favoritos:";

  var grid = document.getElementById("favoritos-grid");
  if (!grid) return;

  var favoritos = getFavoritos();

  if (favoritos.length === 0) {
    grid.innerHTML =
      '<div class="favoritos-vazio">' +
        '<p class="fav-vazio-icone">&#9825;</p>' +
        '<p>Você ainda não favoritou nenhum local.</p>' +
        '<a href="index.html" class="btn-fav-explorar">Explorar locais</a>' +
      '</div>';
    return;
  }

  var itensFavoritos = dados.locais.filter(function(l) {
    return favoritos.indexOf(l.id) !== -1;
  });

  grid.innerHTML = itensFavoritos.map(function(l) {
    return '<article class="card card-favorito" onclick="window.location=\'detalhe.html?id=' + l.id + '\'">' +
      '<div class="card-img-wrap">' +
        '<img src="' + l.imagem_principal + '" alt="' + l.nome + '" loading="lazy">' +
        (l.destaque ? '<span class="badge-destaque">&#11088; Destaque</span>' : '') +
        '<button class="btn-favorito ativo" onclick="toggleFavorito(' + l.id + ', event)" title="Remover dos favoritos">&#9829;</button>' +
      '</div>' +
      '<div class="card-body">' +
        '<span class="card-regiao">' + l.regiao + '</span>' +
        '<h3 class="card-nome">' + l.nome + '</h3>' +
        '<p class="card-desc">' + l.descricao + '</p>' +
        '<a href="detalhe.html?id=' + l.id + '" class="card-link">Ver detalhes &rarr;</a>' +
      '</div>' +
    '</article>';
  }).join("");
}

document.addEventListener("DOMContentLoaded", function() {
  var page = document.body.getAttribute("data-page");

  if (page === "index") {
    renderCarrossel();
    renderCards();
  } else if (page === "detalhe") {
    renderDetalhe();
  } else if (page === "favoritos") {
    var usuario = JSON.parse(sessionStorage.getItem("usuarioCorrente"));
    if (!usuario) {
      window.location.href = "modulos/login/index.html";
      return;
    }
    renderFavoritos();
  }

  var navToggle = document.getElementById("nav-toggle");
  if (navToggle) {
    navToggle.addEventListener("click", function() {
      document.getElementById("nav-mobile").classList.toggle("open");
    });
  }
});

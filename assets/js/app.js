function getLocalPorId(id) {
  return dados.locais.find(function(l) { return l.id === parseInt(id); });
}

function getLocaisDestaque() {
  return dados.locais.filter(function(l) { return l.destaque; });
}

function getTodosLocais() {
  return dados.locais;
}

function getFavoritos() {
  var usuario = JSON.parse(sessionStorage.getItem("usuarioCorrente"));
  if (!usuario) return [];
  var key = "favoritos_" + usuario.id;
  return JSON.parse(localStorage.getItem(key)) || [];
}

function isFavorito(id) {
  return getFavoritos().indexOf(id) !== -1;
}

function toggleFavorito(id, evento) {
  evento.stopPropagation();
  var usuario = JSON.parse(sessionStorage.getItem("usuarioCorrente"));
  if (!usuario) {
    alert("Você precisa estar logado para favoritar um item.\nRedirecionando para o login...");
    window.location.href = "modulos/login/index.html";
    return;
  }
  var key = "favoritos_" + usuario.id;
  var favoritos = JSON.parse(localStorage.getItem(key)) || [];
  var idx = favoritos.indexOf(id);
  if (idx === -1) {
    favoritos.push(id);
  } else {
    favoritos.splice(idx, 1);
  }
  localStorage.setItem(key, JSON.stringify(favoritos));

  var page = document.body.getAttribute("data-page");
  if (page === "favoritos") {
    renderFavoritos();
  } else {
    renderCards();
  }
}

function renderCarrossel() {
  var destaques = getLocaisDestaque();
  var track = document.getElementById("carrossel-track");
  var dots  = document.getElementById("carrossel-dots");
  if (!track) return;

  track.innerHTML = destaques.map(function(l, i) {
    return '<div class="slide" data-index="' + i + '">' +
      '<img src="' + l.imagem_principal + '" alt="' + l.nome + '" loading="lazy">' +
      '<div class="slide-overlay">' +
        '<span class="slide-badge">' + l.tipo + '</span>' +
        '<h2 class="slide-title">' + l.nome + '</h2>' +
        '<p class="slide-desc">' + l.descricao + '</p>' +
        '<a href="detalhe.html?id=' + l.id + '" class="btn-ver">Conhecer &rarr;</a>' +
      '</div>' +
    '</div>';
  }).join("");

  if (dots) {
    dots.innerHTML = destaques.map(function(_, i) {
      return '<button class="dot ' + (i === 0 ? "active" : "") + '" data-dot="' + i + '" aria-label="Slide ' + (i + 1) + '"></button>';
    }).join("");
    dots.querySelectorAll(".dot").forEach(function(d) {
      d.addEventListener("click", function() { goToSlide(parseInt(d.dataset.dot)); });
    });
  }

  var current = 0;
  var timer = setInterval(function() { goToSlide((current + 1) % destaques.length); }, 5000);

  function goToSlide(n) {
    current = n;
    track.style.transform = "translateX(-" + (n * 100) + "%)";
    if (dots) {
      dots.querySelectorAll(".dot").forEach(function(d, i) {
        d.classList.toggle("active", i === n);
      });
    }
    clearInterval(timer);
    timer = setInterval(function() { goToSlide((current + 1) % destaques.length); }, 5000);
  }

  var prev = document.getElementById("prev-btn");
  var next = document.getElementById("next-btn");
  if (prev) prev.addEventListener("click", function() { goToSlide((current - 1 + destaques.length) % destaques.length); });
  if (next) next.addEventListener("click", function() { goToSlide((current + 1) % destaques.length); });
}

function renderCards() {
  var grid = document.getElementById("cards-grid");
  if (!grid) return;
  grid.innerHTML = getTodosLocais().map(function(l) {
    var fav = isFavorito(l.id);
    return '<article class="card' + (fav ? ' card-favorito' : '') + '" onclick="window.location=\'detalhe.html?id=' + l.id + '\'">' +
      '<div class="card-img-wrap">' +
        '<img src="' + l.imagem_principal + '" alt="' + l.nome + '" loading="lazy">' +
        (l.destaque ? '<span class="badge-destaque">&#11088; Destaque</span>' : '') +
        '<button class="btn-favorito' + (fav ? ' ativo' : '') + '" onclick="toggleFavorito(' + l.id + ', event)" title="' + (fav ? 'Remover dos favoritos' : 'Adicionar aos favoritos') + '">' +
          (fav ? '&#9829;' : '&#9825;') +
        '</button>' +
      '</div>' +
      '<div class="card-body">' +
        '<span class="card-regiao">' + l.regiao + '</span>' +
        '<h3 class="card-nome">' + l.nome + '</h3>' +
        '<p class="card-desc">' + l.descricao + '</p>' +
        '<a href="detalhe.html?id=' + l.id + '" class="card-link">Ver detalhes &rarr;</a>' +
      '</div>' +
    '</article>';
  }).join("");
}

